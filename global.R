# Load the reference data (semester, courses, pins).
#
# Each read falls back to data/qrchem_cache.json when the database is
# unreachable, so the app can still start and validate logins during an outage.
# Wrapped so that a failed read can never stop the app from booting.
#
# The cache itself is refreshed automatically on a desktop run.  Hosted platforms
# have an ephemeral filesystem, so the write is skipped there and the copy
# generated by the last desktop run is what ships in the bundle.
#
cacheWriteEnabled = shouldWriteReferenceCache()

tryCatch({
  # specify the semester and load the course information from database
  currentSemester = loadSemester()
  loadCourses(currentSemester)

  # load the admin, dev, and other user pins from database
  adminPin = NULL # read from DB
  devPins = c() # read from DB
  loadPinsFromDB()

  # refresh the on-disk cache from the live values so that whatever gets deployed
  # next is current (no-op if the cache was used, or on a hosted platform)
  if(cacheWriteEnabled) {
    writeReferenceCache()
  }
},
error = function(error_message) {
  print("***Error Loading Reference Data***")
  print(error_message)

  if(!exists("currentSemester")) currentSemester <<- "UNKNOWN"
  if(!exists("coursesDF")) coursesDF <<- NULL
  if(!exists("adminPin")) adminPin <<- NULL
  if(!exists("devPins")) devPins <<- c()
})

